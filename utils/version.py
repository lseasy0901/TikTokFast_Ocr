"""
客户端版本号 —— 全项目唯一来源 (Phase 0)。

契约：
    此文件是版本号的**唯一**定义处。客户端运行时、PyInstaller spec、发布流程
    都必须从这里读取，任何其它地方不得重复书写版本字符串。

为什么单独一个文件
    版本号有三个消费方，且分属不同进程/环境：
        - 客户端运行时（更新检查要拿它和服务器返回的 version 比较）
        - douyin_viewer.spec（构建时读取，写进构建日志与产物标识）
        - 发布流程（给 ZIP / manifest 命名）
    放在最小依赖的独立模块里，这三者才能用最简单的方式读到同一个值，
    而不必为了一个常量去 import 整个 gui / utils 包。

约束：
    本文件**不得**引入任何 import，也不得引入任何计算。spec 是用 exec() 直接
    读取它的 —— 保持"只有一条字面量赋值"这一形态，构建环境才不需要装齐运行时
    依赖也能读到版本号。

版本语义：
    形如 ``MAJOR.MINOR.PATCH`` 的纯数字三段式，供更新系统做数值比较。
    不要在版本号里加入 ``-beta`` / ``+build`` 之类的后缀 —— MVP 的更新检查按
    三段数字逐段比较，非数字段会让比较结果未定义。
"""

